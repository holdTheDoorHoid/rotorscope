//! Rasterise the wide screen's fonts into 4-bit coverage tables.
//!
//! ```text
//! cargo run -p fontgen --release
//! ```
//!
//! Reads the TTFs in `crates/screen/fonts/` (SIL Open Font License, the
//! licence text beside each) and writes `crates/screen/src/wide/glyphs.rs`
//! (metrics) and `glyphs.bin` (bitmaps). Both are committed, so building
//! the firmware needs neither this tool nor the TTFs. Run it again only to
//! change a size or a typeface.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// (role, file, pixel size, digits only).
type Role = (&'static str, &'static str, f32, bool);

/// B612 (Airbus's cockpit typeface): Glass Cockpit and Red Night.
const B612: [Role; 13] = [
    ("label", "b612/B612-Regular.ttf", 13.0, false),
    ("small", "b612/B612-Regular.ttf", 15.0, false),
    ("small_b", "b612/B612-Bold.ttf", 15.0, false),
    ("body", "b612/B612-Regular.ttf", 18.0, false),
    ("body_b", "b612/B612-Bold.ttf", 18.0, false),
    ("title", "b612/B612-Bold.ttf", 24.0, false),
    ("head", "b612/B612-Bold.ttf", 28.0, false),
    ("data", "b612mono/B612Mono-Regular.ttf", 19.0, false),
    ("data_l", "b612mono/B612Mono-Regular.ttf", 24.0, false),
    ("id", "b612mono/B612Mono-Regular.ttf", 30.0, false),
    ("num_m", "b612mono/B612Mono-Bold.ttf", 48.0, true),
    ("num_l", "b612mono/B612Mono-Bold.ttf", 72.0, true),
    ("num_xl", "b612mono/B612Mono-Bold.ttf", 104.0, true),
];

/// IBM Plex Sans Condensed: Field Day (narrow, so a size larger).
const PLEX: [Role; 13] = [
    ("label", "ibmplexsanscondensed/IBMPlexSansCondensed-SemiBold.ttf", 14.0, false),
    ("small", "ibmplexsanscondensed/IBMPlexSansCondensed-Regular.ttf", 16.0, false),
    ("small_b", "ibmplexsanscondensed/IBMPlexSansCondensed-SemiBold.ttf", 16.0, false),
    ("body", "ibmplexsanscondensed/IBMPlexSansCondensed-Regular.ttf", 20.0, false),
    ("body_b", "ibmplexsanscondensed/IBMPlexSansCondensed-SemiBold.ttf", 20.0, false),
    ("title", "ibmplexsanscondensed/IBMPlexSansCondensed-Bold.ttf", 26.0, false),
    ("head", "ibmplexsanscondensed/IBMPlexSansCondensed-Bold.ttf", 30.0, false),
    ("data", "ibmplexsanscondensed/IBMPlexSansCondensed-SemiBold.ttf", 21.0, false),
    ("data_l", "ibmplexsanscondensed/IBMPlexSansCondensed-SemiBold.ttf", 26.0, false),
    ("id", "ibmplexsanscondensed/IBMPlexSansCondensed-SemiBold.ttf", 32.0, false),
    ("num_m", "ibmplexsanscondensed/IBMPlexSansCondensed-Bold.ttf", 52.0, true),
    ("num_l", "ibmplexsanscondensed/IBMPlexSansCondensed-Bold.ttf", 78.0, true),
    ("num_xl", "ibmplexsanscondensed/IBMPlexSansCondensed-Bold.ttf", 112.0, true),
];

fn chars(digits: bool) -> Vec<char> {
    if digits {
        "0123456789.- ".chars().collect()
    } else {
        let mut v: Vec<char> = (32u8..=126).map(char::from).collect();
        v.extend(['\u{b0}', '\u{b7}']);
        v
    }
}

fn main() {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
    let fonts = root.join("crates/screen/fonts");
    let out = root.join("crates/screen/src/wide");
    let mut blob: Vec<u8> = Vec::new();
    let mut rs = String::new();
    rs.push_str(
        "//! GENERATED by `tools/fontgen` from the TTFs in `crates/screen/fonts/`\n\
         //! (SIL Open Font License 1.1). Do not edit; rerun the tool.\n\n\
         use super::font::{Charset, Font, FontSet, Glyph};\n\n\
         static BLOB: &[u8] = include_bytes!(\"glyphs.bin\");\n\n\
         /// The bitmaps of every font.\n\
         pub fn blob() -> &'static [u8] {\n    BLOB\n}\n\n",
    );
    for (set, roles) in [("B612", &B612), ("PLEX", &PLEX)] {
        let mut fields = String::new();
        for &(role, file, px, digits) in roles.iter() {
            let font = load(&fonts.join(file));
            let lm = font.horizontal_line_metrics(px).expect("horizontal metrics");
            let ascent = lm.ascent.ceil() as i32;
            let height = (lm.ascent - lm.descent).ceil() as i32;
            let cap = font.metrics('H', px).height as i32;
            let name = format!("{set}_{}", role.to_uppercase());
            let mut g = String::new();
            for c in chars(digits) {
                let (m, cov) = font.rasterize(c, px);
                let off = blob.len();
                let mut nib = Vec::with_capacity(cov.len());
                for v in &cov {
                    nib.push(((u32::from(*v) * 15 + 127) / 255) as u8);
                }
                for pair in nib.chunks(2) {
                    blob.push(pair[0] << 4 | pair.get(1).copied().unwrap_or(0));
                }
                let top = -(m.ymin + m.height as i32);
                // Big numerals come from a monospaced face, whose "." is as
                // wide as a digit: "1. 4". Close it up.
                // A monospaced face's "." and ":" are as wide as a digit:
                // "1. 4", "14: 03". Close them up (never wider than the
                // face had them).
                let tight = matches!(c, '.' | ':' | ',') && m.width > 0;
                let side = (px * 0.08).round().max(1.0);
                let tight_adv = m.width as f32 + 2.0 * side;
                let (adv, xmin) = if tight && tight_adv < m.advance_width {
                    ((tight_adv * 16.0).round() as u32, side as i32)
                } else {
                    ((m.advance_width * 16.0).round() as u32, m.xmin)
                };
                assert!(m.width < 256 && m.height < 256 && (-128..128).contains(&xmin) && (-128..128).contains(&top));

                writeln!(
                    g,
                    "    Glyph {{ w: {}, h: {}, x: {}, y: {}, adv: {}, off: {} }}, // {:?}",
                    m.width, m.height, xmin, top, adv, off, c
                )
                .unwrap();
            }
            writeln!(rs, "static {name}: [Glyph; {}] = [\n{g}];", chars(digits).len()).unwrap();
            writeln!(
                fields,
                "    {role}: Font {{ px: {}, ascent: {ascent}, height: {height}, cap: {cap}, charset: Charset::{}, glyphs: &{name} }},",
                px as u32,
                if digits { "Digits" } else { "Ascii" }
            )
            .unwrap();
        }
        writeln!(rs, "\npub static {set}: FontSet = FontSet {{\n{fields}}};\n").unwrap();
    }
    std::fs::write(out.join("glyphs.bin"), &blob).unwrap();
    std::fs::write(out.join("glyphs.rs"), rs).unwrap();
    println!("glyphs.bin: {} bytes", blob.len());
}

fn load(p: &Path) -> fontdue::Font {
    let bytes = std::fs::read(p).unwrap_or_else(|e| panic!("{}: {e}", p.display()));
    fontdue::Font::from_bytes(bytes, fontdue::FontSettings::default()).expect("a TTF")
}
